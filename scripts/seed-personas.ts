async function main() {
  const accounts = await prisma.account.findMany({ orderBy: { createdAt: 'asc' } });
  console.log(`총 ${accounts.length}개 계정 대상\n`);

  for (const acc of accounts) {
    const persona = PERSONAS[acc.handle];
    if (!persona) {
      console.log(`⚠️  @${acc.handle}: 매핑 없음, 건너뜀`);
      continue;
    }
    await prisma.account.update({
      where: { id: acc.id },
      data: { personaPrompt: persona },
    });
    console.log(`✅ @${acc.handle}: ${persona.length}자 페르소나 저장`);
  }
  process.exit(0);
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
